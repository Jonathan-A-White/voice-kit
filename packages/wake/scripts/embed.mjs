// Prepares @voice-kit/wake's build (mw-rl10piw.1). Two jobs, no bundler:
//
//   node scripts/embed.mjs           writes src/workerSource.ts: the Web Worker as text. A worker started from a blob: URL
//                                    cannot import './detector.js', so the text is detector.ts and worker.ts transpiled to
//                                    plain JavaScript and joined (detector.ts imports nothing, which is what lets this work).
//                                    The file is committed and tests/wake.test.ts holds it equal to workerText(), so the
//                                    page's source-alias and the built dist run the very same worker. Run before tsc.
//   node scripts/embed.mjs --models  copies every .json under examples/wake-spike/public/models (the trained models and
//                                    licences.json) to dist/models, where the exports map's './wake/models/*' points. Run after tsc.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const PACKAGE = fileURLToPath(new URL('..', import.meta.url));
const MODELS = fileURLToPath(new URL('../../../examples/wake-spike/public/models', import.meta.url));
const OUTPUT = join(PACKAGE, 'src', 'workerSource.ts');

const js = (file) => ts.transpileModule(readFileSync(join(PACKAGE, 'src', file), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;

/** The worker as one plain-JavaScript module: the detector, then the worker's own code with its import of the detector removed. */
export function workerText() {
  const worker = js('worker.ts').replace(/^import \{[^}]*\} from '\.\/detector\.js';\n/m, '');
  if (/^import /m.test(worker) || /^import /m.test(js('detector.ts'))) throw new Error('the worker and the detector may import nothing: a blob: worker has nothing to resolve it against');
  return `${js('detector.ts')}\n${worker}`;
}

/** The text of src/workerSource.ts. */
export function workerSourceFile() {
  return `// GENERATED by scripts/embed.mjs from detector.ts and worker.ts: do not edit. The Web Worker as text, started from a blob: URL.\nexport const workerSource = ${JSON.stringify(workerText())};\n`;
}

/** Copies the models into dist/models. */
export function copyModels() {
  const to = join(PACKAGE, 'dist', 'models');
  mkdirSync(to, { recursive: true });
  const names = readdirSync(MODELS).filter((name) => name.endsWith('.json'));
  for (const name of names) copyFileSync(join(MODELS, name), join(to, name));
  return names;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--models')) console.log(`wake: models copied: ${copyModels().join(', ')}`);
  else {
    writeFileSync(OUTPUT, workerSourceFile());
    console.log('wake: src/workerSource.ts written');
  }
}
